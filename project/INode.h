#pragma once
#include "NodeResult.h"

//======================================================
// INode
// 全ノード共通インターフェース
//======================================================
class INode {
public:
    virtual ~INode() = default;

    //==================================================
    // init
    //--------------------------------------------------
    // ノードが「初めて実行状態（Idle → Running）」に
    // 入る瞬間に一度だけ呼ばれる想定
    //
    // ・タイマー初期化
    // ・内部状態のリセット
    // ・開始時アニメーションの設定
    // などを行う場所
    //
    // ※ 直接呼ばず、execute() 経由で呼ばれる
    //==================================================
    virtual void init() = 0;

    //==================================================
    // tick
    //--------------------------------------------------
    // ノードが Running 状態の間、
    // 毎フレーム呼ばれる更新処理
    //
    // ・距離判定
    // ・移動、回転
    // ・待機時間のカウント
    // など「継続処理」をここに書く
    //
    // 処理の結果として mNodeResult を
    //   Running / Success / Fail
    // のいずれかに更新する。
    //
    // ※ 直接呼ばず、execute() 経由で呼ばれる。
    //==================================================
    virtual void tick() = 0;

    //==================================================
    // finalize
    //--------------------------------------------------
    // ノードの結果が Success または Fail に
    // 確定した瞬間に一度だけ呼ばれる想定。
    //
    // ・後処理
    // ・状態リセット
    // ・親ノードへ制御を返す準備
    // などを行う
    //
    // Composite / Decorator / Branch では
    //   子ノードの Reset()
    //   RunningIndex の初期化
    //   分岐インデックスのクリア
    // などを行う重要なポイント
    //
    // ※ 直接呼ばず、execute() 経由で呼ばれる
    //==================================================
    virtual void finalize() = 0;

    //==================================================
    // get_node_result
    //--------------------------------------------------
    // 現在のノードの状態を返す。
    //
    // 親ノード（Sequence / Selector / Branch）は
    // この結果を見て
    //   ・次の子へ進む
    //   ・自分を Success / Fail にする
    //   ・Running のまま継続する
    // かを判断する
    //==================================================
    virtual NodeResult get_node_result() const = 0;

    //==================================================
     // execute
     //--------------------------------------------------
     // BehaviorTree 実行の唯一の入口
     //
     // 呼び出し側（EnemyAIController など）は
     //   node->execute();
     // だけを呼ぶ
     //
     // この関数の中で：
     //   ・Idle → init()
     //   ・Running → tick()
     //   ・Success / Fail → finalize()
     // の順序が保証される
     //
     // 重要
     //   init / tick / finalize を
     //   外部から直接呼ばないこと
     //==================================================
    virtual void execute() = 0;
};
